"""Generate IDE-specific MCP configs and agent integrations."""

from __future__ import annotations

import json
from pathlib import Path


def detect_ides(project_root: Path) -> list[str]:
    """Detect which IDEs are in use based on directory markers."""
    detected = []
    if (project_root / ".vscode").exists():
        detected.append("vscode")
    if (project_root / ".cursor").exists():
        detected.append("cursor")
    if (project_root / ".idea").exists():
        detected.append("jetbrains")
    if (project_root / ".github").exists():
        detected.append("copilot_cli")
    if (project_root / ".windsurf").exists():
        detected.append("windsurf")
    return detected


def generate_vscode_mcp(project_root: Path, wiki_subdir: str = ".llmwiki") -> Path:
    """Generate .vscode/mcp.json for VS Code Copilot."""
    vscode_dir = project_root / ".vscode"
    vscode_dir.mkdir(exist_ok=True)
    config = {
        "servers": {
            "llmwiki": {
                "type": "stdio",
                "command": "llmwiki",
                "args": ["mcp"],
                "cwd": "${workspaceFolder}/" + wiki_subdir,
            }
        }
    }
    out = vscode_dir / "mcp.json"
    out.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    return out


